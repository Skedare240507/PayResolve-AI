import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const registryFile = path.join(rootDir, 'frontend', 'src', 'lib', 'metricDefinitions.ts');
const docsFile = path.join(rootDir, 'docs', 'metrics.md');

console.log('📖 Generating docs/metrics.md from frontend metric definitions registry...');

const content = fs.readFileSync(registryFile, 'utf8');

// Parse METRIC_REGISTRY object literal
const metricBlocks = content.split(/id:\s*['"]([a-zA-Z0-9_.]+)['"]/g);

const metrics = [];

for (let i = 1; i < metricBlocks.length; i += 2) {
  const id = metricBlocks[i];
  const block = metricBlocks[i + 1] || '';

  const getField = (fieldName) => {
    const match = block.match(new RegExp(`${fieldName}:\\s*['"]([^'"]+)['"]`));
    return match ? match[1] : '';
  };

  metrics.push({
    id,
    label: getField('label'),
    meaning: getField('meaning'),
    formula: getField('formula'),
    source: getField('source'),
    window: getField('window'),
    caveats: getField('caveats') || '—',
    implementation: getField('implementation'),
  });
}

console.log(`📊 Parsed ${metrics.length} metrics for documentation.`);

let md = `# PayResolve Metric Definitions & Calculation Specifications

> **Single Source of Truth:** This file is automatically generated from \`frontend/src/lib/metricDefinitions.ts\` via \`npm run docs:metrics\`. It documents every KPI, percentage, count, duration, and chart metric rendered across PayResolve AI.

---

## Metric Registry Specifications

| Metric ID | Label | Meaning | Formula | Source | Window | Caveats | Implementation Path |
|---|---|---|---|---|---|---|---|
`;

for (const m of metrics) {
  const clean = (str) => (str || '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  md += `| \`${m.id}\` | **${clean(m.label)}** | ${clean(m.meaning)} | ${clean(m.formula)} | \`${clean(m.source)}\` | ${clean(m.window)} | ${clean(m.caveats)} | \`${clean(m.implementation)}\` |\n`;
}

md += `
---

## Material Symbols & Accessibility Compliance
- **Icon:** Google Material Symbols Outlined (\`<GoogleIcon name="info" />\`), Apache-2.0 licensed.
- **Component:** Accessible interactive \`<button type="button">\` with minimum 44×44px hit-box via padding, visible keyboard focus ring, and \`role="tooltip"\`.
- **Positioning Engine:** Powered by \`@floating-ui/react\` (MIT license) with dynamic collision detection, flipping, and shifting to prevent viewport clipping.
- **Real Values Guarantee:** Every derived ratio displays its underlying numerator, denominator, sample size ($n$), and actual measured numbers. No numbers or thresholds are synthesized.
`;

fs.writeFileSync(docsFile, md, 'utf8');
console.log('✅ Successfully wrote docs/metrics.md');
